import {
  addCollectionItemFn,
  addFlightFn,
  addLogFn,
  addToBacklogFn,
  clearFn,
  deleteCollectionItemFn,
  deleteFlightFn,
  deleteLogFn,
  exportAllFn,
  getIndexFn,
  getFactsFn,
  getStatsFn,
  importAllFn,
  importCollectionFn,
  moveLogFn,
  fillFromSteamFn,
  listBacklogFn,
  listCollectionFn,
  listFlightsFn,
  listLibraryFn,
  listLibraryPageFn,
  listLogsFn,
  listRecentFn,
  removeFromBacklogFn,
  updateCollectionItemFn,
  updateFlightFn,
  updateLogFn,
} from "@/server/archive.functions"
import type { ArchiveRepository } from "./types"

/** The archive in Postgres, through server functions (session required). */
export const remoteRepository: ArchiveRepository = {
  listLibrary: (type) => listLibraryFn({ data: { type } }),
  listLibraryPage: (input) => listLibraryPageFn({ data: input }),
  listLogs: (target) => listLogsFn({ data: target }),
  listRecent: (limit) => listRecentFn({ data: { limit } }),
  addLog: (input, item) => addLogFn({ data: { input, item } }),
  updateLog: (id, input) => updateLogFn({ data: { id, input } }),
  moveLog: (id, input, item) => moveLogFn({ data: { id, input, item } }),
  deleteLog: (id) => deleteLogFn({ data: { id } }),
  listBacklog: () => listBacklogFn(),
  addToBacklog: (item) => addToBacklogFn({ data: item }),
  removeFromBacklog: (target) => removeFromBacklogFn({ data: target }),
  getIndex: () => getIndexFn(),
  getStats: () => getStatsFn(),
  getFacts: () => getFactsFn(),
  listCollection: () => listCollectionFn(),
  addCollectionItem: (snapshot, input) =>
    addCollectionItemFn({ data: { snapshot, input } }),
  updateCollectionItem: (id, input) =>
    updateCollectionItemFn({ data: { id, input } }),
  deleteCollectionItem: (id) => deleteCollectionItemFn({ data: { id } }),
  importCollection: (drafts) => importCollectionFn({ data: { drafts } }),
  fillFromSteam: (entries) => fillFromSteamFn({ data: { entries } }),
  listFlights: () => listFlightsFn(),
  addFlight: (input) => addFlightFn({ data: input }),
  updateFlight: (id, input) => updateFlightFn({ data: { id, input } }),
  deleteFlight: (id) => deleteFlightFn({ data: { id } }),
  exportAll: () => exportAllFn(),
  importAll: (data) => importAllFn({ data }),
  clear: () => clearFn(),
}
